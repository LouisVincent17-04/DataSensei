    /** Width in points of a line of text. */
    public static function width(string $text, string $font, float $size, float $letterSpacing = 0.0): float
    {
        $table = self::WIDTHS[$font] ?? self::WIDTHS[self::SANS];
        $encoded = self::encode($text);
        $units = 0;
        $length = strlen($encoded);
        for ($i = 0; $i < $length; $i++) {
            $units += $table[ord($encoded[$i])] ?: 500;
        }

        return $units * $size / 1000 + max(0, $length - 1) * $letterSpacing;
    }

    /**
     * Breaks text into lines no wider than $maxWidth. A word longer than a
     * line is cut. At most $maxLines lines; the last one ends with "..." when
     * text had to be left out.
     *
     * @return list<string>
     */
    public static function wrap(string $text, string $font, float $size, float $maxWidth, int $maxLines = 0, float $letterSpacing = 0.0): array
    {
        $words = preg_split('/\s+/u', trim($text)) ?: [];
        $lines = [];
        $line = '';

        foreach ($words as $word) {
            if ($word === '') {
                continue;
            }

            $candidate = $line === '' ? $word : $line.' '.$word;
            if (self::width($candidate, $font, $size, $letterSpacing) <= $maxWidth) {
                $line = $candidate;
                continue;
            }

            if ($line !== '') {
                $lines[] = $line;
            }

            // A single word wider than the line is cut into pieces.
            while (self::width($word, $font, $size, $letterSpacing) > $maxWidth && mb_strlen($word) > 1) {
                $cut = mb_strlen($word);
                while ($cut > 1 && self::width(mb_substr($word, 0, $cut), $font, $size, $letterSpacing) > $maxWidth) {
                    $cut--;
                }
                $lines[] = mb_substr($word, 0, $cut);
                $word = mb_substr($word, $cut);
            }
            $line = $word;
        }

        if ($line !== '') {
            $lines[] = $line;
        }

        if ($maxLines > 0 && count($lines) > $maxLines) {
            $lines = array_slice($lines, 0, $maxLines);
            $last = rtrim($lines[$maxLines - 1], " .,;:");
            while ($last !== '' && self::width($last.'...', $font, $size, $letterSpacing) > $maxWidth) {
                $last = rtrim(mb_substr($last, 0, -1));
            }
            $lines[$maxLines - 1] = $last.'...';
        }

        return $lines;
    }

    /** The largest size (down to $minSize) at which text fits on one line. */
    public static function fit(string $text, string $font, float $size, float $maxWidth, float $minSize, float $letterSpacing = 0.0): float
    {
        while ($size > $minSize && self::width($text, $font, $size, $letterSpacing) > $maxWidth) {
            $size -= 0.5;
        }

        return $size;
    }

    /** Text in Windows-1252; characters it cannot hold become "?". */
    public static function encode(string $text): string
    {
        $converted = @iconv('UTF-8', 'Windows-1252//TRANSLIT', $text);

        return $converted === false ? (string) preg_replace('/[^\x20-\x7E]/', '?', $text) : $converted;
    }
